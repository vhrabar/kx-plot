"""
Crawler files for the kx-plot docs: sitemap.xml, robots.txt, llms.txt, llms-full.txt and JSON-LD.
"""
from __future__ import annotations

import json
import os
import subprocess
from functools import cache
from typing import TYPE_CHECKING, Any
from urllib.parse import urlsplit
from xml.sax.saxutils import escape

from docutils import nodes
from sphinx import addnodes
from sphinx.writers.text import TextTranslator

if TYPE_CHECKING:
    from sphinx.application import Sphinx
    from sphinx.util.typing import ExtensionMetadata

# pages that are generated, not written: kept out of the sitemap and llms files
SKIP = {"genindex", "search", "py-modindex"}


def _base(app: Sphinx) -> str:
    """The canonical URL of this version, ending in ``/``."""
    base = app.config.html_baseurl or app.config.kx_seo_fallback_url
    return base.rstrip("/") + "/"


def _root(app: Sphinx) -> str:
    """The domain root, where Read the Docs serves the crawler files."""
    parts = urlsplit(_base(app))
    return f"{parts.scheme}://{parts.netloc}/"


def _url(app: Sphinx, docname: str) -> str:
    if docname == app.config.root_doc:
        return _base(app)
    return _base(app) + app.builder.get_target_uri(docname)


def _order(app: Sphinx) -> list[str]:
    """Every document, in toctree order from the root, then any left over."""
    env, seen, out = app.env, set(), []

    def walk(doc: str) -> None:
        if doc in seen or doc not in env.found_docs:
            return
        seen.add(doc)
        out.append(doc)
        for child in env.toctree_includes.get(doc, []):
            walk(child)

    walk(app.config.root_doc)
    out += sorted(d for d in env.found_docs if d not in seen)
    return [d for d in out if d not in SKIP]


def _title(app: Sphinx, docname: str) -> str:
    title = app.env.titles.get(docname)
    return title.astext() if title else docname


def _description(app: Sphinx, docname: str, limit: int = 300) -> str:
    """The first paragraph of the page, trimmed to whole sentences within ``limit`` characters."""
    for para in app.env.get_doctree(docname).findall(nodes.paragraph):
        text = " ".join(para.astext().split())
        if len(text) < 20:  # skip badges and one-word captions
            continue
        if len(text) <= limit:
            return text
        cut = text[:limit]
        end = cut.rfind(". ")
        return cut[: end + 1] if end > 0 else cut.rsplit(" ", 1)[0] + "…"
    return app.config.kx_seo_description


@cache
def _lastmod(path: str) -> str | None:
    """The date of the last commit that touched ``path``, or ``None`` outside git."""
    try:
        out = subprocess.run(["git", "log", "-1", "--format=%cs", "--", path], capture_output=True, text=True,
                             cwd=os.path.dirname(path), check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return None
    return out or None


def _doc_lastmod(app: Sphinx, docname: str) -> str | None:
    """The page source's last commit; for a page generated at build time (untracked), the last commit overall."""
    return _lastmod(app.env.doc2path(docname, base=True).as_posix()) or _lastmod(app.confdir.as_posix())


def _sections(app: Sphinx) -> list[tuple[str, list[str]]]:
    """``(caption, docnames)`` for every internal toctree on the root page."""
    out = []
    for toc in app.env.get_doctree(app.config.root_doc).findall(addnodes.toctree):
        docs = [ref for _, ref in toc["entries"] if ref in app.env.found_docs]
        if docs:
            out.append((toc.get("caption") or "Docs", docs))
    return out


def _page_text(app: Sphinx, docname: str) -> str:
    doctree = app.env.get_and_resolve_doctree(docname, app.builder)
    # the HTML builder's translator class would be picked by TextWriter, so run the text one directly
    visitor = TextTranslator(doctree, app.builder)
    doctree.walkabout(visitor)
    # drop the viewcode "[source]" link text after each signature
    return visitor.body.replace("[source]\n", "\n").strip()


def _write(app: Sphinx, name: str, text: str) -> None:
    with open(os.path.join(app.outdir, name), "w", encoding="utf-8") as f:
        f.write(text)


def write_sitemap(app: Sphinx, docs: list[str]) -> None:
    rows = []
    for doc in docs:
        mod = _doc_lastmod(app, doc)
        rows.append(f"  <url>\n    <loc>{escape(_url(app, doc))}</loc>\n"
                    + (f"    <lastmod>{mod}</lastmod>\n" if mod else "") + "  </url>")
    _write(app, "sitemap.xml", '<?xml version="1.0" encoding="UTF-8"?>\n'
           '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + "\n".join(rows) + "\n</urlset>\n")


def write_robots(app: Sphinx) -> None:
    root = _root(app)
    _write(app, "robots.txt", f"""\
# kx-plot documentation. Generated by docs/_ext/kx_seo.py.
# A plain-text index for language models is at {root}llms.txt, the full docs at {root}llms-full.txt.

User-agent: *
Allow: /
Disallow: /*/search.html
Disallow: /*/genindex.html
Disallow: /*/py-modindex.html
Disallow: /*/_sources/

Sitemap: {root}sitemap.xml
""")


def write_llms(app: Sphinx, docs: list[str]) -> None:
    cfg, root = app.config, _root(app)
    lines = [f"# {cfg.project}", "", f"> {cfg.kx_seo_description}", "", cfg.kx_seo_summary.strip(), ""]
    for caption, section in _sections(app):
        lines += [f"## {caption}", ""]
        lines += [f"- [{_title(app, d)}]({_url(app, d)}): {_description(app, d, 200)}" for d in section]
        lines.append("")
    lines += ["## Optional", "", f"- [Full documentation as plain text]({root}llms-full.txt)"]
    lines += [f"- [{name}]({url})" for name, url in cfg.kx_seo_links.items()]
    _write(app, "llms.txt", "\n".join(lines) + "\n")

    parts = [f"# {cfg.project} {cfg.release}", "", f"> {cfg.kx_seo_description}", "", f"Source: {_base(app)}"]
    for doc in docs:
        parts += ["", "", f"# {_title(app, doc)}", "", f"URL: {_url(app, doc)}", "", _page_text(app, doc)]
    _write(app, "llms-full.txt", "\n".join(parts) + "\n")


def build_finished(app: Sphinx, exception: Exception | None) -> None:
    if exception or app.builder.format != "html":
        return
    docs = _order(app)
    write_sitemap(app, docs)
    write_robots(app)
    write_llms(app, docs)


def _trail(app: Sphinx, docname: str) -> list[str]:
    """The toctree ancestors of ``docname`` from the root down, ending with the page itself."""
    parents = {child: doc for doc, children in app.env.toctree_includes.items() for child in children}
    trail = [docname]
    while trail[-1] != app.config.root_doc and trail[-1] in parents and parents[trail[-1]] not in trail:
        trail.append(parents[trail[-1]])
    if trail[-1] != app.config.root_doc:  # an orphan page: hang it off the home page
        trail.append(app.config.root_doc)
    return trail[::-1]


def _jsonld(app: Sphinx, docname: str) -> str:
    cfg, base = app.config, _base(app)
    author = {"@type": "Person", "name": cfg.author, "url": cfg.kx_seo_author_url}
    website = {"@id": base + "#website"}
    software = {"@id": base + "#software"}
    url = _url(app, docname)
    is_home = docname == cfg.root_doc

    crumbs = [{"@type": "ListItem", "position": i, "name": cfg.project if d == cfg.root_doc else _title(app, d),
               "item": _url(app, d)} for i, d in enumerate(_trail(app, docname), 1)]

    page = {
        "@type": "WebPage" if is_home else "TechArticle",
        "@id": url + "#page",
        "url": url,
        "name": _title(app, docname),
        "description": _description(app, docname),
        "inLanguage": "en",
        "isPartOf": website,
        "about": software,
        "author": author,
    }
    if len(crumbs) > 1:  # a trail of just the home page says nothing
        page["breadcrumb"] = {"@type": "BreadcrumbList", "itemListElement": crumbs}
    if not is_home:
        page["headline"] = page["name"][:110]
    if mod := _doc_lastmod(app, docname):
        page["dateModified"] = mod

    graph = {
        "@context": "https://schema.org",
        "@graph": [
            {**website, "@type": "WebSite", "url": base, "name": f"{cfg.project} documentation",
             "inLanguage": "en", "publisher": author, "about": software},
            {**software, "@type": "SoftwareSourceCode", "name": cfg.project, "description": cfg.kx_seo_description,
             "url": base, "codeRepository": cfg.kx_seo_links["GitHub"], "programmingLanguage": "Python",
             "runtimePlatform": "Python 3", "license": "https://opensource.org/licenses/MIT",
             "version": cfg.release, "author": author, "keywords": cfg.kx_seo_keywords,
             "sameAs": [u for n, u in cfg.kx_seo_links.items() if n != "Gallery"]},
            page,
        ],
    }
    # "</" must not appear inside a <script> element
    return json.dumps(graph, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")


def html_page_context(app: Sphinx, pagename: str, templatename: str, context: dict[str, Any],
                      doctree: nodes.document | None) -> None:
    if pagename not in app.env.found_docs or pagename in SKIP:
        return
    context["kx_jsonld"] = _jsonld(app, pagename)
    context["kx_description"] = _description(app, pagename, 160)


def setup(app: Sphinx) -> ExtensionMetadata:
    app.add_config_value("kx_seo_fallback_url", "", "html")
    app.add_config_value("kx_seo_description", "", "html")
    app.add_config_value("kx_seo_summary", "", "html")
    app.add_config_value("kx_seo_keywords", [], "html")
    app.add_config_value("kx_seo_author_url", "", "html")
    app.add_config_value("kx_seo_links", {}, "html")
    app.connect("html-page-context", html_page_context)
    app.connect("build-finished", build_finished)
    return {"version": "1.0", "parallel_read_safe": True, "parallel_write_safe": True}
